# Simple Priniting Tasks

print("Hello World!") # Print Hello World to the console

print(2 + 3) # Print the sum of 2 and 3 to the console
print(3 - 1) # Print the difference of 3 and 1 to the console
print(3 * 4) # Print the product of 3 and 4 to the console
print(2 / 2) # Print the quotient of 2 and 2 to the console
print(3 ** 3) # Print 3 raised to the power 3 to the console
print(4 % 2) # Print the remainder of 4 divided by 2 to the console
print(7 // 2) # Print the floor division of 7 divided by 2 to the console

# Checking Data Types

print(type(10)) # Print int to the console
print(type(10.5)) # Print float
print(type(1 + 3j)) # Print complex
print(type('Rameen')) # Print string
print(type([1, 2, 3])) # Print list
print(type({'name' : 'Rameen'})) # Print dictionary
print(type({9.4, 3.7, 2,7})) # Print set
