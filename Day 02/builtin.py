# Some built in functions in Python

print("Hello, World!") # Print Hello, World! to the console
print(len("Rameen")) # Print the length of the string
print(type("Water")) # Print data type
print(str(10)) # Convert 10 to string and then print it
print(int("10")) # Convert string to intger
print(float(10)) # Convert to float and then print it
# help("keywords") # Print all the keywords in python
print(min(10, 20, 30)) # Print the minimum value
print(max(1, 2, 3)) # Print the maximum value
print(min([10, 20, 30])) # Takes list as an argument and print the minimum value
print(max([20, 30, 40, 50])) # Takes list as an argument and print the maximum value
print(sum([1, 2, 3, 4])) # Takes list as an argument and print the sum of all the values

